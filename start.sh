#!/usr/bin/env bash
# ======================================================================
#  FinSight 酒研助手 · Linux / macOS 启动脚本
#  用法：./start.sh
# ======================================================================
set -euo pipefail

cd "$(dirname "$0")"

# ---- 1. 依赖检查 -----------------------------------------------------
if ! command -v uv >/dev/null 2>&1; then
    echo "[错误] 没有找到 uv，请先安装： https://docs.astral.sh/uv/"
    exit 1
fi

# ---- 2. 环境变量检查 -------------------------------------------------
if [ -z "${DEEPSEEK_API_KEY:-}" ] && [ ! -f .env ]; then
    echo "[错误] 缺少 DEEPSEEK_API_KEY"
    echo "       请设置环境变量，或复制 .env.example 为 .env 并填写"
    exit 1
fi

# ---- 3. 同步依赖 -----------------------------------------------------
echo "[1/2] 同步依赖（uv sync）"
uv sync

# ---- 4. 启动服务 -----------------------------------------------------
echo "[2/2] 启动服务：http://127.0.0.1:8003"
echo "       首次启动要加载 Milvus 集合和 BGE-M3 模型，约 30-60 秒属正常"
echo
exec uv run python app.py
